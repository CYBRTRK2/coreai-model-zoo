# --------------------------------------------------------------------------- request helpers
def noul(instructions=None, criteria=None):
    q = {"type": "noul"}
    if instructions is not None:
        q["instructions"] = instructions
    if criteria is not None:
        q["criteria"] = criteria
    return q


def choice(instructions, criteria):
    q = {"type": "choice"}
    if instructions is not None:
        q["instructions"] = instructions
    q["criteria"] = criteria
    return q


def score(instructions, levels):
    q = {"type": "score"}
    if instructions is not None:
        q["instructions"] = instructions
    q["criteria"] = list(levels)
    return q


def record(rid, source, state, questions, gold=None, note="", provenance=None):
    out = {"id": rid, "source": source, "request": {"model": MODEL, "state": state, "questions": questions},
           "gold": gold or {}, "note": note}
    if provenance is not None:
        out["provenance"] = provenance
    return out


# --------------------------------------------------------------------------- transfer-v4 slices
def read_transfer_v4(fetch: bool) -> list[dict]:
    path = Path(TRANSFER_V4["local"])
    if path.exists():
        raw = path.read_bytes()
    elif fetch:
        with urllib.request.urlopen(TRANSFER_V4["raw_url"], timeout=60) as r:
            raw = r.read()
    else:
        raise SystemExit(f"{path} not found: clone the author's repository at tag kev-1.0 there, or pass --fetch")
    assert hashlib.sha256(raw).hexdigest() == TRANSFER_V4["sha256"], "transfer-v4 development.jsonl changed"
    lines = raw.decode("utf-8").splitlines()
    assert len(lines) == TRANSFER_V4["lines"]
    return [json.loads(line) for line in lines]


def gold_key(q):
    """A transfer-v4 label -> the question_keys entry: choice = the criteria name, noul = bool, score = level index."""
    y = q["label"]
    if q["type"] == "choice":
        assert y in q["criteria"], y
        return y
    if q["type"] == "noul":
        assert isinstance(y, bool), y
        return "true" if y else "false"
    assert isinstance(y, int) and 0 <= y < len(q["criteria"]), y
    return str(y)


def tv4_record(rid, source, line_no, r):
    questions = {qid: {k: v for k, v in q.items() if k in ("type", "instructions", "criteria")} for qid, q in r["questions"].items()}
    gold = {qid: gold_key(q) for qid, q in r["questions"].items()}
    prov = {"file": TRANSFER_V4["path_in_repo"], "line": line_no, "src": {qid: q.get("src") for qid, q in r["questions"].items()},
            "_meta": r["_meta"]}
    return record(rid, source, r["state"], questions, gold, note=f"{r['_meta'].get('source')} {r['_meta'].get('id')}", provenance=prov)


def transfer_v4_records(rows):
    tv4 = [tv4_record(f"tv4_{i:03d}", "transfer_v4_dev_head", i, rows[i]) for i in range(TV4_N)]
    assert all(r["provenance"]["_meta"]["source"] == "mmlu" for r in tv4)
    tv4x = []
    for src in TV4X_SOURCES:
        picked = [(i, r) for i, r in enumerate(rows) if r["_meta"]["source"] == src][:TV4X_PER_SOURCE]
        assert len(picked) == TV4X_PER_SOURCE, src
        tv4x += [tv4_record(f"tv4x_{src}_{k:02d}", "transfer_v4_dev_sources", i, r) for k, (i, r) in enumerate(picked)]
    scored = [(i, r) for i, r in enumerate(rows) if any(q["type"] == "score" for q in r["questions"].values())][:TV4S_N]
    tv4s = [tv4_record(f"tv4s_{k:02d}", "transfer_v4_dev_score", i, r) for k, (i, r) in enumerate(scored)]
    assert len(tv4s) == TV4S_N
    lines = [r["provenance"]["line"] for r in tv4 + tv4x + tv4s]
    assert len(lines) == len(set(lines)), "a transfer-v4 line is in two slices"
    return tv4, tv4x, tv4s


def heldout_records(rows):
    """The held-out slices (`--heldout`): mmlu records 61-100, records 21-30 of each other source, score records
    21-40, all in file order; none of their lines is in the fixture's slices."""
    lo, hi = TV4H_RANGE
    mmlu = [(i, r) for i, r in enumerate(rows) if r["_meta"]["source"] == "mmlu"][lo:hi]
    assert len(mmlu) == hi - lo
    tv4h = [tv4_record(f"tv4h_{k:02d}", "transfer_v4_dev_head_heldout", i, r) for k, (i, r) in enumerate(mmlu)]
    tv4xh = []
    lo, hi = TV4XH_RANGE
    for src in TV4X_SOURCES:
        picked = [(i, r) for i, r in enumerate(rows) if r["_meta"]["source"] == src][lo:hi]
        assert len(picked) == hi - lo, src
        tv4xh += [tv4_record(f"tv4xh_{src}_{k:02d}", "transfer_v4_dev_sources_heldout", i, r) for k, (i, r) in enumerate(picked)]
    lo, hi = TV4SH_RANGE
    scored = [(i, r) for i, r in enumerate(rows) if any(q["type"] == "score" for q in r["questions"].values())][lo:hi]
    assert len(scored) == hi - lo
    tv4sh = [tv4_record(f"tv4sh_{k:02d}", "transfer_v4_dev_score_heldout", i, r) for k, (i, r) in enumerate(scored)]
    held = tv4h + tv4xh + tv4sh
    lines = [r["provenance"]["line"] for r in held]
    fx = {r["provenance"]["line"] for r in sum(transfer_v4_records(rows), [])}
    assert len(lines) == len(set(lines)), "a transfer-v4 line is in two held-out slices"
    assert not set(lines) & fx, "a held-out line is in the fixture"
    return held


