    s = doc["summary"]
    print(f"{path}: {s['records']} records, {s['questions']} questions, rows {s['row_tokens']}, sha256 {hashlib.sha256(data).hexdigest()}")
    for src, v in s["by_source"].items():
        print(f"  {src}: {v['records']} records, {v['questions']} questions, {v['types']}, options {v['options']}")
    return 0


